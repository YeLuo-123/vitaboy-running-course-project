// Select a small, reproducible backup without uploading anything.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(root, 'BACKUP_MANIFEST.json');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const posix = value => value.split(path.sep).join('/');
const fail = message => { throw new Error(message); };
const absolute = relative => {
  const result = path.resolve(root, relative);
  if (!result.startsWith(root + path.sep)) fail(`Path outside project: ${relative}`);
  return result;
};
const readJson = async relative => JSON.parse((await fs.readFile(absolute(relative), 'utf8')).replace(/^\uFEFF/, ''));

if (process.argv.includes('--verify')) {
  const manifest = await readJson('BACKUP_MANIFEST.json');
  for (const entry of manifest.files) {
    const bytes = await fs.readFile(absolute(entry.path));
    if (bytes.length !== entry.bytes || hash(bytes) !== entry.sha256) fail(`Hash mismatch: ${entry.path}`);
  }
  console.log(`Verified ${manifest.files.length} files (${(manifest.total_bytes / 1048576).toFixed(2)} MiB).`);
} else {
  const policy = await readJson('backup_policy.json');
  const selected = new Set(policy.files);
  for (const directory of policy.source_roots) {
    for (const item of await fs.readdir(absolute(directory), { withFileTypes: true })) {
      if (item.isFile() && policy.source_extensions.includes(path.extname(item.name))) selected.add(`${directory}/${item.name}`);
    }
  }
  async function visit(directory) {
    for (const item of await fs.readdir(absolute(directory), { withFileTypes: true })) {
      const relative = `${directory}/${item.name}`;
      if (item.isSymbolicLink()) fail(`Symlink must be reviewed before backup: ${relative}`);
      if (item.isDirectory() && !['.git', '.venv', '__pycache__', 'node_modules'].includes(item.name)) await visit(relative);
      if (item.isFile() && (policy.tree_extensions.includes(path.extname(item.name)) || policy.tree_license_names.includes(item.name))) selected.add(relative);
    }
  }
  for (const directory of policy.trees) await visit(directory);

  // Exact file allowlist: an accidental git add . cannot include videos/models/logs.
  const gitPaths = [...selected, '.gitignore', 'BACKUP_MANIFEST.json'].sort();
  const allow = new Set();
  for (const relative of gitPaths) {
    const parts = relative.split('/');
    for (let i = 1; i < parts.length; i++) allow.add(`!/${parts.slice(0, i).join('/')}/`);
    allow.add(`!/${relative}`);
  }
  await fs.writeFile(path.join(root, '.gitignore'), '# Generated by tools/prepare_backup.mjs from backup_policy.json.\n# Re-run the tool before staging newly selected files.\n*\n' + [...allow].join('\n') + '\n', 'utf8');
  selected.add('.gitignore');

  const credentialPatterns = [
    /-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----/,
    /\bgh[pousr]_[A-Za-z0-9]{20,}\b/,
    /\bgithub_pat_[A-Za-z0-9_]{30,}\b/,
    /\bAKIA[0-9A-Z]{16}\b/,
    /https?:\/\/[^\s/:]+:[^\s/@]+@[^\s/]+/,
    /(?:api[_-]?key|access[_-]?token|client[_-]?secret|password)\s*[:=]\s*["'][A-Za-z0-9+/=_-]{16,}["']/i
  ];
  const binaryExtensions = new Set(['.onnx', '.npz', '.png', '.jpg']);
  const files = [];
  for (const relative of [...selected].sort()) {
    const stat = await fs.lstat(absolute(relative));
    if (!stat.isFile() || stat.isSymbolicLink()) fail(`Not a regular file: ${relative}`);
    if (stat.size > 10 * 1048576) fail(`Large file requires explicit review: ${relative}`);
    if (/\.(mp4|mov|avi|pt|pth|pkl|apk|pptx|pdf|pem|key|log)$/i.test(relative)) fail(`Excluded file type: ${relative}`);
    const bytes = await fs.readFile(absolute(relative));
    if (!binaryExtensions.has(path.extname(relative))) {
      const text = bytes.toString('utf8');
      if (credentialPatterns.some(pattern => pattern.test(text))) fail(`Potential credential found in ${relative}; value withheld.`);
      if (path.extname(relative) === '.json') JSON.parse(text.replace(/^\uFEFF/, ''));
    }
    files.push({ path: posix(relative), bytes: bytes.length, sha256: hash(bytes) });
  }
  const manifest = {
    schema_version: 1,
    snapshot_scope: 'Selected local project files; remote-only checkpoints and logs excluded',
    hash_algorithm: 'SHA-256 over original file bytes; manifest does not hash itself',
    total_bytes: files.reduce((sum, item) => sum + item.bytes, 0),
    file_count_excluding_manifest: files.length,
    files
  };
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  console.log(`Prepared ${files.length + 1} files including manifest (${(manifest.total_bytes / 1048576).toFixed(2)} MiB payload).`);
}
